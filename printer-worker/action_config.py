from typing import Optional, Dict, List
from pydantic import BaseModel

# Статусы из IntraService
STATUS_IN_PROGRESS = 27  # В работе
STATUS_WAITING = 35      # Требует уточнения
STATUS_ON_HOLD = 40      # На доработку
STATUS_RESOLVED = 29     # Выполнена

class ActionRule(BaseModel):
    status_id: Optional[int] = None
    comment_template: Optional[str] = None

# Конструктор действий воркера
# Доступные переменные для шаблона (в фигурных скобках):
# {printer_name} - название принтера (из драйвера)
# {target_pc} - имя целевого компьютера
# {error} - текст ошибки (если есть)
# {connection_type} - тип подключения (USB, NETWORK, и т.д.)
ACTIONS: Dict[str, ActionRule] = {
    # Успешное завершение установки
    "on_success": ActionRule(
        status_id=STATUS_RESOLVED,
        comment_template="Здравствуйте! Принтер {printer_name} был успешно установлен на ваш компьютер {target_pc}."
    ),
    
    # Ошибка: Отключен USB-кабель
    "on_usb_disconnected": ActionRule(
        status_id=STATUS_WAITING,
        comment_template=(
            "Здравствуйте!\n\n"
            "Не вижу МФУ.\n"
            "1. Убедитесь в корректности имени принтера;\n"
            "2. Перезагрузите МФУ;\n"
            "3. Переподключите usb кабель к МФУ;\n"
            "Если МФУ не заработает перезвоните на номер 49-87."
        )
    ),
    
    # Глобальная ошибка автоустановки
    "on_error": ActionRule(
        status_id=None,
        comment_template=None
    ),
    
    # Ошибка: Потеряно внутреннее состояние (Redis)
    "on_state_lost": ActionRule(
        status_id=None,
        comment_template=None
    ),
    
    # Восстановление сиротских задач (зависла при перезапуске сервера)
    "on_orphan_recovered": ActionRule(
        status_id=None,
        comment_template=None
    )
}

